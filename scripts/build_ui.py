"""Package the shared panel for the two native Hermes loaders. No third-party build tools."""
import argparse
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
panel = (root / 'dashboard/panel.js').read_text()
style = (root / 'dashboard/dist/style.css').read_text()

dashboard = """// Generated by scripts/build_ui.py from dashboard/panel.js.
(() => {
  'use strict';
  const sdk = window.__HERMES_PLUGIN_SDK__;
  const api = (path, data) => sdk.fetchJSON('/api/plugins/ryzeapi' + path, data === undefined ? {} : {
    method: 'POST', headers: { 'Content-Type': 'application/json', 'X-Ryze-UI': '1' }, body: JSON.stringify(data)
  });
""" + panel + """
  const App = createRyzePanel(sdk.React, sdk.components, api);
  window.__HERMES_PLUGINS__.register('ryzeapi', () => sdk.React.createElement('div', {className: 'ryze-surface'}, sdk.React.createElement(App)));
})();
"""
desktop = """// Generated by scripts/build_ui.py from the same panel as the Dashboard.
import * as React from 'react';
import { ROUTES_AREA, SIDEBAR_NAV_AREA } from '@hermes/plugin-sdk';
""" + panel + """
const h = React.createElement;
function Button({ outlined, children, ...props }) {
  return h('button', {...props, className: outlined ? 'ryze-secondary' : 'ryze-primary'}, children);
}
export default {
  id: 'ryzeapi', name: 'RyzeAPI',
  register(ctx) {
    const api = (path, data) => ctx.rest(path, data === undefined ? {} : {method: 'POST', body: {...data, _ryze_ui: true}, timeoutMs: 90000});
    const App = createRyzePanel(React, { Button, Input: 'input', Label: 'label' }, api);
    for (const [id, path, webhooksPage] of [['whatsapp', '/ryzeapi', false], ['webhooks', '/ryzeapi/webhooks', true]]) {
      ctx.register({
        id, area: ROUTES_AREA, data: {path},
        render: () => h('div', {className: 'ryze-desktop ryze-surface'},
          h('style', null, STYLE), h(App, {webapp: true, webhooksPage}))
      });
    }
    ctx.register({id: 'nav', area: SIDEBAR_NAV_AREA,
      data: {path: '/ryzeapi', label: 'RyzeAPI', codicon: 'comment-discussion'}});

  }
};
""".replace('STYLE', json.dumps(style, ensure_ascii=False))

parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
for path, content in ((root / 'plugin.js', desktop), (root / 'dashboard/dist/index.js', dashboard)):
    if args.check:
        if not path.exists() or path.read_text() != content:
            raise SystemExit(f'Out of date: {path.name}')
    else:
        path.write_text(content)
